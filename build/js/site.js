/* SHAZWAN© — motion and behaviour, every timing taken from the Hanza template source:
   - smooth scroll: Lenis 1.3.23 defaults (lerp .1, anchors)
   - text reveal: Framer "appear" text effect by LINE, each line opacity .001/y20 -> in, spring .8s bounce 0,
     +.05s per line, start delay per element (data-tx), once, on view
   - appear: y10 / y50 springs .8s bounce 0 with hand delays; orange squares scale 0 -> 1 spring .6s, delay .2,
     replayed every time they re-enter (threshold .5)
   - scroll scrub: offsets run from "reference section enters the bottom of the viewport" to "its bottom reaches
     the bottom of the viewport"; the hero runs over its own height from the top of the page
   - counters: spring 1s bounce 0, once     - ticker: 40 px/s
   - menu: backdrop spring .3s, panel y30 -> 0 spring .6s     - buttons/links: spring .4s bounce .2 (CSS)
   window.SPRINGS holds the CSS linear() versions of those springs (generated by build.py). */
(function () {
  "use strict";
  var doc = document, root = doc.documentElement, W = window;
  var S = W.SPRINGS || {};
  var reduce = W.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var lin = W.CSS && CSS.supports && CSS.supports("animation-timing-function", "linear(0, 1)");
  var ez = function (k, fb) { return lin && S[k] ? S[k] : fb; };
  var E08 = ez("s08", "cubic-bezier(.22,1,.36,1)"), E06 = ez("s06", "cubic-bezier(.22,1,.36,1)"),
      E05 = ez("s05", "cubic-bezier(.22,1,.36,1)"), E03 = ez("s03", "cubic-bezier(.22,1,.36,1)"),
      E04b = ez("s04b2", "cubic-bezier(.34,1.35,.64,1)"), ESOFT = ez("soft", "cubic-bezier(.16,1,.3,1)");
  var SOFT_MS = S.soft_ms || 1600;
  var isPhone = function () { return W.matchMedia("(max-width: 809.98px)").matches; };
  var canAnim = typeof Element.prototype.animate === "function";
  // button + link hover springs use the template's .4s/bounce .2 spring
  if (lin && S.s04b2) { root.style.setProperty("--btn-e", S.s04b2); root.style.setProperty("--roll-e", S.s04b2); }

  /* scrollbar width -> --sbw so column maths (100vw based) matches the layout width */
  function sbw() { root.style.setProperty("--sbw", (W.innerWidth - root.clientWidth) + "px"); }
  sbw(); W.addEventListener("resize", sbw);

  /* ---------------------------------------------------------- smooth scroll */
  var lenis = null;
  if (!reduce && W.Lenis) {
    lenis = new W.Lenis({ lerp: 0.1, smoothWheel: true, anchors: true, autoRaf: true });
    W.lenis = lenis;
  }
  var onScroll = [];
  var ticking = false;
  function frame() { ticking = false; for (var i = 0; i < onScroll.length; i++) onScroll[i](); }
  function req() { if (!ticking) { ticking = true; requestAnimationFrame(frame); } }
  W.addEventListener("scroll", req, { passive: true });
  W.addEventListener("resize", req);
  if (lenis) lenis.on("scroll", req);

  /* ---------------------------------------------------------- local time */
  doc.querySelectorAll("[data-clock]").forEach(function (el) {
    var tz = el.getAttribute("data-clock");
    var fmt = function () {
      try { el.textContent = new Date().toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit", hour12: true, timeZone: tz }); }
      catch (e) { el.textContent = ""; }
    };
    fmt(); setInterval(fmt, 15000);
  });

  /* ---------------------------------------------------------- giant wordmark fit */
  function fitWordmarks() {
    var probe = doc.createElement("span");
    probe.style.cssText = "position:absolute;visibility:hidden;white-space:nowrap;font-size:100px;letter-spacing:-.045em;text-transform:uppercase;font-family:" + getComputedStyle(doc.body).fontFamily + ";font-weight:500";
    doc.querySelectorAll(".wm span").forEach(function (s) {
      probe.textContent = s.textContent; doc.body.appendChild(probe);
      var w = probe.getBoundingClientRect().width; probe.remove();
      if (w) s.style.setProperty("--wmk", (99.2 / w).toFixed(5));
    });
  }

  /* ---------------------------------------------------------- IO helper */
  function onView(els, fn, opts) {
    if (!els.length) return;
    if (!("IntersectionObserver" in W)) { els.forEach(function (el) { fn(el, true); }); return; }
    var once = !opts || opts.once !== false;
    var io = new IntersectionObserver(function (ents) {
      ents.forEach(function (en) {
        if (en.isIntersecting) { fn(en.target, true); if (once) io.unobserve(en.target); }
        else if (!once) fn(en.target, false);
      });
    }, { threshold: (opts && opts.threshold) || 0 });
    els.forEach(function (el) { io.observe(el); });
  }
  function play(el, kf, ms, delay, easing) {
    if (!canAnim || reduce) { var last = kf[kf.length - 1]; for (var k in last) el.style[k] = last[k]; return null; }
    return el.animate(kf, { duration: ms, delay: (delay || 0) * 1000, easing: easing, fill: "both" });
  }

  /* ---------------------------------------------------------- text reveal by line */
  function splitWords(el) {
    if (el.__split) return el.__split;
    var words = [];
    (function walk(node) {
      Array.prototype.slice.call(node.childNodes).forEach(function (n) {
        if (n.nodeType === 3) {
          var parts = n.textContent.split(/(\s+)/), frag = doc.createDocumentFragment();
          parts.forEach(function (p) {
            if (!p) return;
            if (/^\s+$/.test(p)) { frag.appendChild(doc.createTextNode(" ")); return; }
            var s = doc.createElement("span"); s.className = "tx-line"; s.textContent = p; frag.appendChild(s); words.push(s);
          });
          n.parentNode.replaceChild(frag, n);
        } else if (n.nodeType === 1 && !n.classList.contains("tx-line")) walk(n);
      });
    })(el);
    el.__split = words;
    return words;
  }
  function revealText(el) {
    var words = splitWords(el);
    var start = parseFloat(el.getAttribute("data-tx")) || 0;
    var line = -1, lastTop = null;
    words.forEach(function (w) {
      var t = w.offsetTop;
      if (lastTop === null || Math.abs(t - lastTop) > 2) { line++; lastTop = t; }
      play(w, [{ opacity: 0.001, transform: "translateY(20px)" }, { opacity: 1, transform: "translateY(0px)" }], 800, start + 0.05 * line, E08);
    });
    el.classList.add("tx-ready");
  }
  var txEls = Array.prototype.slice.call(doc.querySelectorAll("[data-tx]"));
  var fontsReady = doc.fonts && doc.fonts.ready ? doc.fonts.ready : Promise.resolve();
  fontsReady.then(function () {
    fitWordmarks();
    txEls.forEach(splitWords);
    onView(txEls, function (el) { revealText(el); });
  });
  // never leave text hidden if fonts take forever
  setTimeout(function () { txEls.forEach(function (el) { if (!el.classList.contains("tx-ready")) { splitWords(el); revealText(el); } }); }, 4000);

  /* ---------------------------------------------------------- appear */
  var AP = {
    y10: function (el, d) { play(el, [{ opacity: 0.001, transform: "translateY(10px)" }, { opacity: 1, transform: "translateY(0px)" }], 800, d, E08); },
    y50: function (el, d) { play(el, [{ opacity: 0, transform: "translateY(50px)" }, { opacity: 1, transform: "translateY(0px)" }], 800, d, E08); },
    zoom12: function (el, d) { play(el, [{ transform: "scale(1.2)" }, { transform: "scale(1)" }], SOFT_MS, d, ESOFT); },
    zoom12s: function (el, d) { play(el, [{ transform: "scale(1.2)" }, { transform: "scale(1)" }], SOFT_MS, d, ESOFT); },
    zoom12h: function (el, d) { play(el, [{ transform: "scale(1.2)" }, { transform: "scale(1)" }], SOFT_MS, d || 0.6, ESOFT); },
    zoom11h: function (el, d) { play(el, [{ transform: "scale(1.1)" }, { transform: "scale(1)" }], SOFT_MS, d || 0.6, ESOFT); }
  };
  onView(Array.prototype.slice.call(doc.querySelectorAll("[data-ap]")), function (el) {
    var f = AP[el.getAttribute("data-ap")]; if (f) f(el, parseFloat(el.getAttribute("data-ap-d")) || 0);
  });
  // orange squares: scale in every time they come into view
  doc.querySelectorAll("[data-pop]").forEach(function (el) {
    if (!("IntersectionObserver" in W) || reduce) { el.style.transform = "none"; return; }
    var th = parseFloat(el.getAttribute("data-pop-th")) || 0.5;
    new IntersectionObserver(function (ents) {
      ents.forEach(function (en) {
        if (el.__a) el.__a.cancel();
        el.__a = en.isIntersecting ? play(el, [{ transform: "scale(0)" }, { transform: "scale(1)" }], 600, 0.2, E06)
                                   : play(el, [{ transform: "scale(1)" }, { transform: "scale(0)" }], 600, 0, E06);
      });
    }, { threshold: th }).observe(el);
  });

  /* ---------------------------------------------------------- counters */
  function easeFn(str) {
    if (!str || str.indexOf("linear(") !== 0) return function (t) { return 1 - Math.pow(1 - t, 3); };
    var pts = str.slice(7, -1).split(",").map(parseFloat);
    return function (t) { var x = t * (pts.length - 1), i = Math.floor(x); if (i >= pts.length - 1) return 1; return pts[i] + (pts[i + 1] - pts[i]) * (x - i); };
  }
  var E1fn = easeFn(S.s1);
  onView(Array.prototype.slice.call(doc.querySelectorAll("[data-count]")), function (el) {
    var to = parseFloat(el.getAttribute("data-count")) || 0;
    if (reduce) { el.textContent = to; return; }
    var t0 = null;
    (function step(ts) {
      if (t0 === null) t0 = ts;
      var p = Math.min(1, (ts - t0) / 1000);
      el.textContent = Math.round(to * E1fn(p));
      if (p < 1) requestAnimationFrame(step);
    })(performance.now());
    setTimeout(function () { el.textContent = to; }, 1300);
  });

  /* ---------------------------------------------------------- scroll-linked transforms */
  function parse(s) { var o = {}; (s || "").split(";").forEach(function (kv) { var p = kv.split(":"); if (p[1]) o[p[0].trim()] = parseFloat(p[1]); }); return o; }
  var scrubs = [];
  doc.querySelectorAll("[data-scrub],[data-scrub-to]").forEach(function (el) {
    var to = el.hasAttribute("data-scrub-to");
    var refMode = el.getAttribute("data-scrub-ref") || "sec";
    var sec = el.closest("[data-sec]");
    var ref = refMode === "next" ? (sec && sec.nextElementSibling) : sec;
    scrubs.push({ el: el, v: parse(el.getAttribute(to ? "data-scrub-to" : "data-scrub")), to: to, ref: ref || sec, hero: refMode === "self-top", cols: !to });
  });
  function applyScrub() {
    var vh = W.innerHeight, sy = W.scrollY || W.pageYOffset, phone = isPhone();
    scrubs.forEach(function (s) {
      if (s.cols && phone) { s.el.style.transform = ""; return; }
      var r = s.ref.getBoundingClientRect(), p;
      if (s.hero) p = Math.min(1, Math.max(0, sy / r.height));
      else p = Math.min(1, Math.max(0, (vh - r.top) / r.height));
      var k = s.to ? p : 1 - p, v = s.v, tf = "";
      if (v.y !== undefined) tf += "translateY(" + (v.y * k).toFixed(2) + "px) ";
      if (v.scale !== undefined) tf += "scale(" + (1 + (v.scale - 1) * k).toFixed(4) + ")";
      s.el.style.transform = tf || "none";
      if (v.opacity !== undefined) s.el.style.opacity = (1 + (v.opacity - 1) * k).toFixed(3);
    });
  }
  var pars = Array.prototype.slice.call(doc.querySelectorAll("[data-parallax]"));
  function applyParallax() {
    var vh = W.innerHeight;
    pars.forEach(function (el) {
      var box = el.parentElement.getBoundingClientRect();
      if (box.bottom < -50 || box.top > vh + 50) return;
      var amt = (parseFloat(el.getAttribute("data-parallax")) || 30) / 100;
      var p = (vh - box.top) / (vh + box.height);          // 0 entering bottom -> 1 leaving top
      el.style.transform = "translate3d(0," + ((p - 0.5) * amt * box.height).toFixed(2) + "px,0)";
    });
  }
  /* mission paragraph: word-by-word reveal tied to scroll (start 90%, end 50%, dim .2) */
  var rws = Array.prototype.slice.call(doc.querySelectorAll("[data-reveal-words]")).map(function (el) {
    var words = [];
    (function walk(node) {
      Array.prototype.slice.call(node.childNodes).forEach(function (n) {
        if (n.nodeType === 3) {
          var frag = doc.createDocumentFragment();
          n.textContent.split(/(\s+)/).forEach(function (p) {
            if (!p) return;
            if (/^\s+$/.test(p)) { frag.appendChild(doc.createTextNode(p)); return; }
            var s = doc.createElement("span"); s.className = "rw"; s.textContent = p; s.style.opacity = ".2"; frag.appendChild(s); words.push(s);
          });
          n.parentNode.replaceChild(frag, n);
        } else if (n.nodeType === 1) walk(n);
      });
    })(el);
    return { el: el, words: words };
  });
  function applyReveal() {
    var vh = W.innerHeight;
    rws.forEach(function (o) {
      var r = o.el.getBoundingClientRect(), a = vh * 0.9, b = vh * 0.5;
      var s = Math.min(Math.max((a - r.top) / (r.height + (a - b)), 0), 1);
      var n = o.words.length, u = Math.floor(s * n);
      for (var i = 0; i < n; i++) {
        o.words[i].style.opacity = i < u ? "1" : i === u ? String(0.2 + (s * n - u) * 0.8) : "0.2";
      }
    });
  }
  /* stacking project cards: card i eases back as card i+1 covers it (0 = next card just touching, 1 = fully covering) */
  var stacks = Array.prototype.slice.call(doc.querySelectorAll("[data-stack]"));
  // stack items: full panels, rows of two cards, or (on phones, where rows are display:contents) the cards themselves
  function stackItems(st) {
    var out = [];
    Array.prototype.forEach.call(st.children, function (c) {
      if (getComputedStyle(c).display === "contents") out.push.apply(out, c.children); else out.push(c);
    });
    return out.filter(function (c) { return c.offsetParent !== null && /\b(panel|prow|wcard)\b/.test(c.className); });
  }
  function applyStack() {
    var vh = W.innerHeight;
    stacks.forEach(function (st) {
      var items = stackItems(st);
      items.forEach(function (c, i) {
        var h = c.offsetHeight;
        // rows/cards stick at their CSS offset, or higher if they are taller than the space below it
        if (!c.classList.contains("panel")) {
          if (c.__base === undefined) { c.style.top = ""; c.__base = parseFloat(getComputedStyle(c).top) || 0; }
          var want = Math.min(c.__base, vh - h);
          if (c.__top !== want) { c.style.top = want + "px"; c.__top = want; }
        }
        var nx = items[i + 1];
        if (!nx || reduce) { c.style.transform = ""; return; }
        var top = parseFloat(getComputedStyle(c).top) || 0;
        var p = Math.min(1, Math.max(0, (top + h - nx.getBoundingClientRect().top) / h));
        c.style.transform = p > 0 ? "scale(" + (1 - 0.08 * p).toFixed(4) + ")" : "";
      });
    });
  }
  W.addEventListener("resize", function () {
    stacks.forEach(function (st) { st.querySelectorAll(".prow, .wcard").forEach(function (c) { c.__base = undefined; c.__top = undefined; c.style.transform = ""; }); });
  });
  onScroll.push(applyScrub, applyParallax, applyReveal, applyStack);
  req();

  /* ---------------------------------------------------------- logo ticker (40 px/s) */
  doc.querySelectorAll("[data-ticker]").forEach(function (row) {
    var anim = null;
    function setup() {
      if (anim) anim.cancel();
      var half = row.scrollWidth / 2;
      if (!half || reduce || !canAnim) return;
      anim = row.animate([{ transform: "translateX(0)" }, { transform: "translateX(" + (-half) + "px)" }], { duration: half / 40 * 1000, iterations: Infinity });
    }
    fontsReady.then(setup);
    var t; W.addEventListener("resize", function () { clearTimeout(t); t = setTimeout(setup, 200); });
  });

  /* ---------------------------------------------------------- menu */
  var menuEl = doc.querySelector("[data-menu]"), tog = doc.querySelector("[data-menu-toggle]");
  if (menuEl && tog) {
    var bg = menuEl.querySelector(".menu__bg"), panel = menuEl.querySelector(".menu__panel"), open = false, anims = [];
    var setMenu = function (o) {
      if (o === open) return; open = o;
      anims.forEach(function (a) { a.cancel(); }); anims = [];
      tog.setAttribute("aria-expanded", o ? "true" : "false");
      menuEl.setAttribute("aria-hidden", o ? "false" : "true");
      if (o) menuEl.classList.add("is-open");
      var a1 = play(bg, o ? [{ opacity: 0 }, { opacity: 1 }] : [{ opacity: 1 }, { opacity: 0 }], 300, 0, E03);
      var a2 = play(panel, o ? [{ opacity: 0, transform: "translateY(30px)" }, { opacity: 1, transform: "translateY(0)" }]
                             : [{ opacity: 1, transform: "translateY(0)" }, { opacity: 0, transform: "translateY(30px)" }], o ? 600 : 300, 0, o ? E06 : E03);
      if (a1) anims.push(a1); if (a2) anims.push(a2);
      if (!o) { if (a2) a2.onfinish = function () { if (!open) menuEl.classList.remove("is-open"); }; else menuEl.classList.remove("is-open"); }
    };
    tog.addEventListener("click", function () { setMenu(!open); });
    menuEl.addEventListener("click", function (e) { if (e.target.closest("[data-menu-close]") || e.target.closest("a")) setMenu(false); });
    doc.addEventListener("keydown", function (e) { if (e.key === "Escape") setMenu(false); });
  }

  /* ---------------------------------------------------------- accordions */
  // the template's phone FAQ starts with every item closed
  if (isPhone()) doc.querySelectorAll("[data-acc] .acc__item.is-open").forEach(function (it) { it.classList.remove("is-open"); it.querySelector(".acc__h").setAttribute("aria-expanded", "false"); });
  doc.querySelectorAll("[data-acc]").forEach(function (acc) {
    var single = acc.hasAttribute("data-single");
    acc.addEventListener("click", function (e) {
      var h = e.target.closest(".acc__h"); if (!h) return;
      var item = h.closest(".acc__item"), o = !item.classList.contains("is-open");
      if (single) acc.querySelectorAll(".acc__item.is-open").forEach(function (it) { if (it !== item) toggle(it, false); });
      toggle(item, o);
    });
  });
  function toggle(item, o) {
    var p = item.querySelector(".acc__p"), from = p.getBoundingClientRect().height;
    item.classList.toggle("is-open", o);
    item.querySelector(".acc__h").setAttribute("aria-expanded", o ? "true" : "false");
    var to = o ? p.scrollHeight : 0;
    if (p.__a) p.__a.cancel();
    if (canAnim && !reduce) {
      p.__a = p.animate([{ height: from + "px" }, { height: to + "px" }], { duration: 500, easing: E05 });
      p.__a.onfinish = function () { p.__a = null; if (lenis) lenis.resize(); };
    }
  }

  /* ---------------------------------------------------------- filters + load more */
  doc.querySelectorAll("[data-filters]").forEach(function (bar) {
    var list = doc.querySelector("[data-filter-items]"); if (!list) return;
    var items = Array.prototype.slice.call(list.children);
    var more = doc.querySelector("[data-load-more]");
    var size = function () {
      if (!list.hasAttribute("data-page-size")) return 1e9;
      if (isPhone()) return +list.getAttribute("data-page-size-p");
      if (W.matchMedia("(max-width: 1279.98px)").matches) return +list.getAttribute("data-page-size-t");
      return +list.getAttribute("data-page-size");
    };
    var cur = "all", shown = size();
    function apply() {
      var n = 0;
      items.forEach(function (it) {
        var k = it.getAttribute("data-kind") || it.getAttribute("data-cat");
        var match = cur === "all" || k === cur;
        it.classList.toggle("is-hidden", !match);
        if (match) { n++; it.classList.toggle("is-paged", n > shown); } else it.classList.remove("is-paged");
      });
      if (more) more.parentElement.hidden = n <= shown;
      if (lenis) lenis.resize();
      req();
    }
    bar.addEventListener("click", function (e) {
      var b = e.target.closest("[data-filter]"); if (!b) return;
      bar.querySelectorAll(".filt").forEach(function (x) { x.classList.toggle("is-on", x === b); });
      cur = b.getAttribute("data-filter"); shown = size(); apply();
    });
    if (more) more.addEventListener("click", function () {
      more.classList.add("is-loading");
      setTimeout(function () { more.classList.remove("is-loading"); shown += size(); apply(); }, 600);
    });
    apply();
  });

  /* ---------------------------------------------------------- contact form (FormSubmit) */
  doc.querySelectorAll("[data-form]").forEach(function (form) {
    var b = form.querySelector(".btn--form"), label = b.querySelector(".btn__t");
    var txt = { incomplete: "Form Incomplete", ready: "Send Message", sending: "Sending ...", sent: "Message Sent", error: "Try Again" };
    function set(s) { b.setAttribute("data-state", s); label.textContent = txt[s]; b.disabled = s === "sending"; }
    function check() { if (b.getAttribute("data-state") === "sending") return; set(form.checkValidity() ? "ready" : "incomplete"); }
    form.addEventListener("input", check);
    form.addEventListener("submit", function (e) {
      e.preventDefault();
      if (!form.checkValidity()) { form.reportValidity(); return; }
      set("sending");
      var data = new FormData(form);
      fetch(form.action, { method: "POST", headers: { Accept: "application/json" }, body: data })
        .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { return r.ok && j.success !== "false"; }); })
        .then(function (ok) { if (ok) { set("sent"); form.reset(); setTimeout(check, 4000); } else set("error"); })
        .catch(function () { set("error"); });
    });
  });
  doc.querySelectorAll("[data-news]").forEach(function (f) {
    f.addEventListener("submit", function (e) { e.preventDefault(); f.querySelector("button").textContent = "Coming soon"; });
  });

  /* ---------------------------------------------------------- page transition flavour (leaving Home) */
  W.addEventListener("pagereveal", function (e) {
    try {
      var from = W.navigation && W.navigation.activation && W.navigation.activation.from;
      if (e.viewTransition && from && /\/(index\.html)?$/.test(new URL(from.url).pathname) && !/\/portfolio\/|\/blog\/|\/about\/|\/contact\/|\/terms\/|\/privacy\//.test(new URL(from.url).pathname)) {
        root.classList.add("from-home");
        e.viewTransition.finished.finally(function () { root.classList.remove("from-home"); });
      }
    } catch (err) {}
  });
})();
